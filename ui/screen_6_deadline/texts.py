"""Тексты экрана указания срока выполнения заказа."""


def get_screen_6_deadline_text() -> str:
    """Возвращает подсказку указать срок в часах.

    Отсчёт часов начинается не при публикации, а с момента, когда заказчик
    выберет исполнителя, — так задача остаётся честной по времени для обеих
    сторон, даже если отклики появятся не сразу.
    """

    return "Укажите срок выполнения\nВведите количество часов на выполнение (отсчёт начнётся с момента выбора исполнителя)"


DEADLINE_INVALID_TEXT = "Срок должен быть положительным целым числом часов. Попробуйте ещё раз."


def get_deadline_hours_text(deadline_hours: int) -> str:
    """Форматирует срок в виде «N ч. после выбора исполнителя»."""

    return f"{deadline_hours} ч. после выбора исполнителя"


def get_deadline_display_text(deadline, deadline_hours: int) -> str:
    """Показывает точную дату, если исполнитель уже выбран, иначе — срок в часах.

    Используется карточками заказа: пока заказ открыт, точная дата дедлайна
    ещё не определена, и заказ показывает только длительность.
    """

    if deadline is not None:
        return deadline.strftime("%d.%m.%Y %H:%M")
    return get_deadline_hours_text(deadline_hours)
